graalvmNative {
    binaries.named("main") {
        imageName = "bergacast"
        // Portable machine code: the build host CPU is not the one the serverless platform runs on.
        buildArgs.add("-march=compatibility")
        // Only glibc stays dynamic, so that a minimal distroless runtime image is enough.
        buildArgs.add("-H:+StaticExecutableWithDynamicLibC")
        // Optimize for size: smaller image and resident code, for a negligible throughput cost on this I/O-bound app.
        buildArgs.add("-Os")
    }
    // The CI runs the JVM tests; the native image is checked end to end by the smoke test.
    testSupport = false
}

