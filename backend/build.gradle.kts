tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.compilerArgs.add("-parameters")
}

// Strict lint on hand-written code only: the sources generated by Spring AOT (compileAot*Java) are not ours.
listOf(tasks.compileJava, tasks.compileTestJava).forEach { compileTask ->
    compileTask.configure { options.compilerArgs.addAll(listOf("-Xlint:all,-serial,-processing", "-Werror")) }
}

val openApiSpecFile = layout.buildDirectory.file("openapi.json")
val openApiExportTestClass = "fr.bergadev.bergacast.config.OpenApiSpecExportTest"

tasks.test {
    useJUnitPlatform()
    systemProperty("bergacast.openapi.output", openApiSpecFile.get().asFile.absolutePath)
    finalizedBy(tasks.jacocoTestReport)
}

tasks.register<Test>("generateOpenApiSpec") {
    description = "Writes the OpenAPI document of the running application to build/openapi.json."
    group = "documentation"
    testClassesDirs =
        sourceSets.test
            .get()
            .output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    useJUnitPlatform()
    filter { includeTestsMatching(openApiExportTestClass) }
    systemProperty("bergacast.openapi.output", openApiSpecFile.get().asFile.absolutePath)
    outputs.file(openApiSpecFile)
    outputs.upToDateWhen { false }
}

